export const LENS_BY_ID = new Map(LENSES.map((l) => [l.id, l]));

/** Минимум: одна практическая и одна экспертная. Регуляторика по желанию. */
export function validateSelection(ids) {
  const chosen = ids.map((id) => LENS_BY_ID.get(id)).filter(Boolean);
  const problems = [];
  if (chosen.length !== ids.length) problems.push('в списке есть неизвестная линза');
  if (chosen.length < 2) problems.push('линз меньше двух');
  if (chosen.length > 4) problems.push('линз больше четырёх, заметка превратится в обзор');
  if (!chosen.some((l) => l.group === 'practice')) problems.push('нет ни одной практической линзы');
  if (!chosen.some((l) => l.group === 'insight')) problems.push('нет ни одной экспертной линзы');
  return problems;
}

/** Сочетание линз как ключ: по нему проверяется, что заметки не повторяются. */
export const combinationKey = (ids) => [...ids].sort().join('+');
